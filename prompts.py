def build_system_prompt(
    subject: str = "informatics",
    condition: str | None = None,
    grade: str | None = None,
    summary: str | None = None,
    reference: str | None = None,
    closed: bool = False,
) -> str:
    """Собираем системный промпт наставника из блоков.

    Андрей: closed=True — задача уже решена и закрыта, условие остаётся в промпте
    только справочником для уточняющих вопросов. Иначе модель посреди нового
    разговора сама возвращается к старой задаче («давай вернёмся к КОЛОБОКу»,
    прогон 8 ноября).
    """
    parts: list[str] = []
    parts.append("Ты — Сократ, дружелюбный учебный наставник. Разбираешь с учеником задачу вопросами и подсказками.")

    # Андрей: 1. Якорь — условие неприкосновенно, идет в КАЖДЫЙ промпт первым блоком
    if condition and closed:
        parts.append(
            f"[РЕШЁННАЯ ЗАДАЧА]\n{condition}\n"
            "Задача выше уже решена и закрыта. Условие здесь только для уточняющих вопросов о том "
            "решении. САМ не возвращайся к ней, не продолжай её разбор и не предлагай вернуться: "
            "ученик сам скажет «продолжим», если захочет, или пришлёт новую задачу."
        )
    elif condition:
        parts.append(
            f"[УСЛОВИЕ ЗАДАЧИ]\n{condition}\n"
            "Условие выше — неприкосновенный якорь: не искажай, не сокращай, не заменяй его. "
            "Весь разбор ведётся только по этому условию."
        )

    # Андрей: 2. Профиль + уровень ученика
    g = grade if grade in GRADE_LABELS else "unknown"
    parts.append(f"[ПРОФИЛЬ]\nУровень ученика: {GRADE_LABELS[g]}.")
    parts.append(f"[УРОВЕНЬ УЧЕНИКА]\n{LEVEL_RULES[g]}")

    # Андрей: 3. Резюме вытесненных ходов
    parts.append("[РЕЗЮМЕ РАННИХ ХОДОВ]\n" + (summary or "Пока пусто — диалог только начался."))

    # Андрей: 4. База предмета
    parts.append(SUBJECT_BASE.get(subject, _GENERIC_SUBJECT_BASE.format(subject=subject)))

    # Андрей: 5. Правила Сократа, 6. Границы роли (тексты Алёны)
    parts.append(SOKRAT_RULES)
    parts.append(ROLE_BOUNDARY)

    # Андрей: 7. Исполнитель в задаче (МТ/Робот/Редактор/Черепаха/Автомат) — блок трассировки
    if condition and any(m in condition.lower() for m in EXECUTOR_CONDITION_MARKERS):
        parts.append(EXECUTOR_TUTOR_BLOCK)

    # Андрей: 8. Эталонная трасса решателя — программный расчёт для сверки шагов ученика
    if reference:
        parts.append(REFERENCE_RULES + "\n\n" + reference)
    return "\n\n".join(parts)
