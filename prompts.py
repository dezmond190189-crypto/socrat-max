# Андрей: «я в 7 классе» главнее всех остальных маркеров
CLASS_RE = re.compile(r"(?:в\s*)?(\d{1,2})\s*[-–]?\s*(?:й|го|ом|ом\b)?\s*класс", re.IGNORECASE)

# Андрей: маркер → уровень; проверяются сверху вниз, первое совпадение выигрывает
GRADE_MARKERS: list[tuple[str, list[str]]] = [
    ("10-11", ["егэ", "кегэ", "демоверсия", "редактор", "черепаха", "автомат"]),
    ("9", ["огэ", "кумир", "робот", "№15", "№16", "номер 15", "номер 16", "задание 15", "задание 16", "номер15", "номер16"]),
    ("6-8", ["алгоритм", "цикл", "массив", "двоичн", "система счисления", "систем счисления",
             "программ", "переменн", "ветвлени", "исполнител"]),
    ("1-5", ["файл", "папк", "каталог", "телефон", "компьютер"]),
]

# Андрей: простая арифметика вида «12 + 5» → 1-5 классы
SIMPLE_ARITH_RE = re.compile(r"\b\d{1,3}\s*[+\-*/]\s*\d{1,3}\b")

GRADE_LABELS = {
    "1-5": "начальная школа (1–5 класс)",
    "6-8": "средняя школа (6–8 класс)",
    "9": "9 класс, готовится к ОГЭ",
    "10-11": "старшая школа (10–11 класс, готовится к ЕГЭ)",
    "unknown": "неизвестен — определи по ходу диалога",
}


def detect_grade(text: str) -> str:
    """Андрей: возвращает один из уровней — 1-5, 6-8, 9, 10-11, unknown."""
    low = (text or "").lower()
    m = CLASS_RE.search(low)
    if m:  # Андрей: названный класс главнее всего
        n = int(m.group(1))
        if 1 <= n <= 5:
            return "1-5"
        if 6 <= n <= 8:
            return "6-8"
        if n == 9:
            return "9"
        if 10 <= n <= 11:
            return "10-11"
        # Андрей: «11 класс» уже поймали; прочие числа (1920 год и т.п.) игнорируем
    for grade, markers in GRADE_MARKERS:
        if any(marker in low for marker in markers):
            return grade
    if SIMPLE_ARITH_RE.search(low):
        return "1-5"
    return "unknown"


